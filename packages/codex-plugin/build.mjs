/** Build the distributable plugin runtime; installation never runs a package manager. */
import { build } from 'esbuild';
import { isBuiltin } from 'node:module';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zipSync } from 'fflate';
import { buildFigmaPlugin } from '../figma-plugin/build.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const bridge = JSON.parse(await readFile(join(here, '../bridge/package.json'), 'utf8'));
const check = process.argv.includes('--check');
const result = await build({
  absWorkingDir: repo,
  entryPoints: ['packages/bridge/src/index.ts'],
  outfile: 'packages/codex-plugin/runtime/bridge.mjs',
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  minify: true,
  legalComments: 'inline',
  write: false,
  metafile: true,
  define: { __BRIDGE_VERSION__: JSON.stringify(bridge.version) },
  // Bundled CommonJS dependencies still use require() for Node built-ins.
  banner: { js: '// Generated by packages/codex-plugin/build.mjs. Do not edit.\nimport { createRequire as __createRequire } from "node:module";\nconst require = __createRequire(import.meta.url);' },
});

// A published plugin must have no dependency on node_modules or checkout paths.
for (const output of Object.values(result.metafile.outputs)) {
  for (const entry of output.imports) {
    if (entry.external && !isBuiltin(entry.path)) throw new Error(`Unbundled dependency: ${entry.path}`);
  }
}

// Include complete licenses for packages that actually contribute to the bundle.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let dir = dirname(resolve(repo, input));
  while (dir !== dirname(dir)) {
    const raw = await readFile(join(dir, 'package.json'), 'utf8').catch(() => null);
    if (raw) {
      const pkg = JSON.parse(raw);
      // Some dependencies have nested package.json files containing only "type".
      if (pkg.name && pkg.version) { packages.set(dir, pkg); break; }
    }
    dir = dirname(dir);
  }
}
let notices = `Codex Figma Bridge bundled dependencies\n\nBridge license:\n${await readFile(join(repo, 'LICENSE'), 'utf8')}`;
for (const [dir, pkg] of [...packages.entries()].sort((a, b) => a[1].name.localeCompare(b[1].name, 'en'))) {
  const files = (await readdir(dir)).filter((name) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name)).sort();
  if (!files.length) throw new Error(`Missing license text for ${pkg.name}`);
  notices += `\n\n--- ${pkg.name}@${pkg.version} (${pkg.license ?? 'see license'}) ---\n`;
  for (const name of files) notices += `\n${name}\n${await readFile(join(dir, name), 'utf8')}`;
}
const outputs = new Map(result.outputFiles.map((file) => [file.path, file.contents]));
outputs.set(join(here, 'runtime/THIRD_PARTY_NOTICES.txt'), Buffer.from(notices + '\n'));
// Build from source in memory, never package a potentially stale dist/ directory.
const figmaFiles = await buildFigmaPlugin();
figmaFiles.set('manifest.json', await readFile(join(here, '../figma-plugin/manifest.json')));
figmaFiles.set('INSTALL.md', await readFile(join(here, 'assets/figma-plugin/INSTALL.md')));
figmaFiles.set('LICENSE', await readFile(join(repo, 'LICENSE')));
const pluginManifest = JSON.parse(await readFile(join(here, '.codex-plugin/plugin.json'), 'utf8'));
figmaFiles.set('VERSION.txt', Buffer.from(`Codex Figma Bridge plugin ${pluginManifest.version}\n`));
const archiveFiles = Object.fromEntries([...figmaFiles].sort(([a], [b]) => a.localeCompare(b, 'en'))
  .map(([name, bytes]) => [`codex-figma-plugin/${name}`, [bytes, { mtime: new Date(1980, 0, 1) }]]));
const archive = zipSync(archiveFiles, { level: 9 });
outputs.set(join(here, 'assets/figma-plugin/codex-figma-plugin.zip'), Buffer.from(archive));
for (const [path, bytes] of outputs) {
  if (check) {
    const existing = await readFile(path).catch(() => null);
    if (!existing?.equals(Buffer.from(bytes))) throw new Error(`Outdated or missing ${relative(repo, path)}. Run pnpm --filter @codex-figma/codex-plugin build and include runtime/ and assets/figma-plugin/ in the plugin release.`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes);
  }
}
console.log(check ? 'Bundled Bridge and Figma ZIP are up to date.' : `Bundled Bridge: ${result.outputFiles[0].contents.length} bytes; Figma ZIP: ${archive.length} bytes. No installation-time builds or npm dependencies.`);
